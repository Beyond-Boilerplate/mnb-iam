export JAVA_HOME="$JAVA_HOME"
export IIQ_HTTP_PORT="$IIQ_HTTP_PORT"
export IIQ_URL="http://localhost:${IIQ_HTTP_PORT}/identityiq"
export IIQ_ADMIN_USER="$IIQ_ADMIN_USER"
export IIQ_DB_HOST="$IIQ_DB_HOST"
export IIQ_DB_PORT="$IIQ_DB_PORT"
export IIQ_TOMCAT_VERSION="$IIQ_TOMCAT_VERSION"
export IIQ_INSTALLED_MYSQL="${IIQ_INSTALLED_MYSQL:-0}"
export IIQ_INSTALLED_TOMCAT="${IIQ_INSTALLED_TOMCAT:-0}"
export IIQ_INSTALLED_JDK="${IIQ_INSTALLED_JDK:-0}"
