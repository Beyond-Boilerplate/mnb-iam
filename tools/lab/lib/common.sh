}

mysql_cli() {
  local bin=""
  if [[ -n "${IIQ_MYSQL_BIN:-}" && -x "${IIQ_MYSQL_BIN}/mysql" ]]; then
    bin="${IIQ_MYSQL_BIN}/mysql"
  elif [[ -x /opt/homebrew/opt/mysql@8.4/bin/mysql ]]; then
    bin="/opt/homebrew/opt/mysql@8.4/bin/mysql"
  elif [[ -x "$IIQ_LAB_HOME/mysql/dist/bin/mysql" ]]; then
    bin="$IIQ_LAB_HOME/mysql/dist/bin/mysql"
  elif command -v mysql >/dev/null 2>&1; then
    bin="$(command -v mysql)"
  else
    die "mysql client not found"
  fi

  local args=()
  if [[ -n "${IIQ_MYSQL_SOCKET:-}" && -S "${IIQ_MYSQL_SOCKET}" ]]; then
    args+=(--socket="$IIQ_MYSQL_SOCKET")
  else
    args+=(-h "${IIQ_DB_HOST:-127.0.0.1}" -P "${IIQ_DB_PORT:-3307}")
  fi
  "$bin" "${args[@]}" "$@"
}

mysql_root_ok() {
  if [[ -n "${MYSQL_ROOT_PASSWORD:-}" ]]; then
    mysql_cli -u root -p"$MYSQL_ROOT_PASSWORD" -e "SELECT 1" >/dev/null 2>&1 && return 0
  fi
  mysql_cli -u root -e "SELECT 1" >/dev/null 2>&1
}

mysql_root() {
  if [[ -n "${MYSQL_ROOT_PASSWORD:-}" ]]; then
    if mysql_cli -u root -p"$MYSQL_ROOT_PASSWORD" -e "SELECT 1" >/dev/null 2>&1; then
      mysql_cli -u root -p"$MYSQL_ROOT_PASSWORD" "$@"
      return
    fi
  fi
  if mysql_cli -u root -e "SELECT 1" >/dev/null 2>&1; then
    mysql_cli -u root "$@"
    return
  fi
  die "Cannot connect to lab MySQL as root. Is the lab mysqld running? Try: iiq-mysql-start"
}

wait_http() {
  local url="$1"
  local seconds="${2:-180}"
  local i=0
  log "Waiting for $url (up to ${seconds}s)…"
  while (( i < seconds )); do
    if curl -fsS -o /dev/null --max-time 3 "$url" 2>/dev/null; then
      log "HTTP OK: $url"
      return 0
    fi
    sleep 2
    i=$((i + 2))
  done
  return 1
}

tomcat_is_running() {
  load_lab_env
  [[ -n "${CATALINA_HOME:-}" ]] || return 1
  port_in_use "${IIQ_HTTP_PORT:-8080}"
}
