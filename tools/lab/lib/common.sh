#!/usr/bin/env bash
# Shared helpers for IdentityIQ local lab scripts.
# shellcheck disable=SC2034

set -euo pipefail

# Resolve paths at source-time (this file lives in tools/lab/lib/)
_IIQ_COMMON_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
_IIQ_LAB_SCRIPTS_DIR="$(cd "${_IIQ_COMMON_DIR}/.." && pwd)"
_IIQ_REPO_ROOT="$(cd "${_IIQ_LAB_SCRIPTS_DIR}/../.." && pwd)"

iiq_scripts_dir() { printf '%s\n' "$_IIQ_LAB_SCRIPTS_DIR"; }
iiq_repo_root() { printf '%s\n' "$_IIQ_REPO_ROOT"; }

# Persistent lab state (created by setup, read by aliases/teardown)
IIQ_LAB_STATE_DIR="${IIQ_LAB_STATE_DIR:-$HOME/.iiq-lab}"
IIQ_LAB_ENV_FILE="${IIQ_LAB_ENV_FILE:-$IIQ_LAB_STATE_DIR/env}"
IIQ_LAB_LOG_DIR="${IIQ_LAB_LOG_DIR:-$IIQ_LAB_STATE_DIR/logs}"

# Defaults (overridable via env before running setup)
IIQ_LAB_HOME="${IIQ_LAB_HOME:-$HOME/iiq-lab}"
IIQ_TOMCAT_VERSION="${IIQ_TOMCAT_VERSION:-9.0.120}"
IIQ_HTTP_PORT="${IIQ_HTTP_PORT:-8080}"
IIQ_HEAP_MS="${IIQ_HEAP_MS:-1024m}"
IIQ_HEAP_MX="${IIQ_HEAP_MX:-2048m}"
IIQ_IMPORT_LCM="${IIQ_IMPORT_LCM:-1}"
IIQ_ADMIN_USER="${IIQ_ADMIN_USER:-spadmin}"
IIQ_ADMIN_PASS="${IIQ_ADMIN_PASS:-admin}"

# DB defaults match identityiq create script
IIQ_DB_HOST="${IIQ_DB_HOST:-127.0.0.1}"
IIQ_DB_PORT="${IIQ_DB_PORT:-3307}"
IIQ_DB_NAME="${IIQ_DB_NAME:-identityiq}"
IIQ_DB_USER="${IIQ_DB_USER:-identityiq}"
IIQ_DB_PASS="${IIQ_DB_PASS:-identityiq}"
IIQ_DB_AH_NAME="${IIQ_DB_AH_NAME:-identityiqah}"
IIQ_DB_AH_USER="${IIQ_DB_AH_USER:-identityiqah}"
IIQ_DB_AH_PASS="${IIQ_DB_AH_PASS:-identityiqah}"
IIQ_DB_PLUGIN_NAME="${IIQ_DB_PLUGIN_NAME:-identityiqPlugin}"
IIQ_DB_PLUGIN_USER="${IIQ_DB_PLUGIN_USER:-identityiqPlugin}"
IIQ_DB_PLUGIN_PASS="${IIQ_DB_PLUGIN_PASS:-identityiqPlugin}"

IIQ_INSTALLED_MYSQL="${IIQ_INSTALLED_MYSQL:-0}"
IIQ_INSTALLED_TOMCAT="${IIQ_INSTALLED_TOMCAT:-0}"
IIQ_INSTALLED_JDK="${IIQ_INSTALLED_JDK:-0}"

log()  { printf '==> %s\n' "$*"; }
warn() { printf 'WARNING: %s\n' "$*" >&2; }
die()  { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

need_cmd() {
  command -v "$1" >/dev/null 2>&1 || die "Required command not found: $1"
}

is_macos() { [[ "$(uname -s)" == "Darwin" ]]; }

# shellcheck disable=SC1091
source "${_IIQ_COMMON_DIR}/bootstrap.sh"

# Hard wrappers used by setup/teardown
resolve_java_home() {
  resolve_java_home_soft || die "JDK 11 or 17 required and could not be installed automatically. See scripts/README.md"
}

resolve_mysql_bin_dir() {
  resolve_mysql_bin_dir_soft || die "MySQL binaries not found. Re-run setup (bootstrap installs mysql@8.4 or a portable tarball)."
}

load_lab_env() {
  if [[ -f "$IIQ_LAB_ENV_FILE" ]]; then
    # shellcheck disable=SC1090
    source "$IIQ_LAB_ENV_FILE"
  fi
}

